#include "SkyboxCube.h"
#include <glad/glad.h>
#include "debug_utils.h"

SkyboxCube::SkyboxCube() {
    setup();
}

void SkyboxCube::setup() {
    // 36 个顶点，每个三角形一个面，总共 12 个三角形
    float skyboxVertices[] = {
        // positions          
        -1.0f,  1.0f, -1.0f,
        -1.0f, -1.0f, -1.0f,
         1.0f, -1.0f, -1.0f,
         1.0f, -1.0f, -1.0f,
         1.0f,  1.0f, -1.0f,
        -1.0f,  1.0f, -1.0f,

        -1.0f, -1.0f,  1.0f,
        -1.0f, -1.0f, -1.0f,
        -1.0f,  1.0f, -1.0f,
        -1.0f,  1.0f, -1.0f,
        -1.0f,  1.0f,  1.0f,
        -1.0f, -1.0f,  1.0f,

         1.0f, -1.0f, -1.0f,
         1.0f, -1.0f,  1.0f,
         1.0f,  1.0f,  1.0f,
         1.0f,  1.0f,  1.0f,
         1.0f,  1.0f, -1.0f,
         1.0f, -1.0f, -1.0f,

        -1.0f, -1.0f,  1.0f,
        -1.0f,  1.0f,  1.0f,
         1.0f,  1.0f,  1.0f,
         1.0f,  1.0f,  1.0f,
         1.0f, -1.0f,  1.0f,
        -1.0f, -1.0f,  1.0f,

        -1.0f,  1.0f, -1.0f,
         1.0f,  1.0f, -1.0f,
         1.0f,  1.0f,  1.0f,
         1.0f,  1.0f,  1.0f,
        -1.0f,  1.0f,  1.0f,
        -1.0f,  1.0f, -1.0f,

        -1.0f, -1.0f, -1.0f,
        -1.0f, -1.0f,  1.0f,
         1.0f, -1.0f, -1.0f,
         1.0f, -1.0f, -1.0f,
        -1.0f, -1.0f,  1.0f,
         1.0f, -1.0f,  1.0f
    };

    vao_ = std::make_unique<VertexArray>();
    vbo_ = std::make_unique<VertexBuffer>(skyboxVertices, sizeof(skyboxVertices), GL_STATIC_DRAW);

    vao_->bind();
    // layout location 0: 位置坐标 (vec3)
    vao_->setAttribute(0, *vbo_, 3, GL_FLOAT, GL_FALSE, 0, 3 * sizeof(float), 0);
    vao_->unbind();

    GL_CHECK_ERROR();
}

void SkyboxCube::render() const {
    vao_->bind();
    glDrawArrays(GL_TRIANGLES, 0, 36);
    vao_->unbind();
    GL_CHECK_ERROR();
}